first = int(input("Enter the first integer: "))
second = int(input("Enter the second integer: "))
third = int(input("Enter the third integer: "))

mult1 = first*first
mult2 = second*second
mult3 = third*third

sum = mult1 + mult2 + mult3

print(f"Here is the equation:")
print(f"{first}x{first} + {second}x{second} + {third}x{third} = {mult1} + {mult2} + {mult3} = {sum}")